-- พื้นที่กดบนภาพ (สิ่งที่ LINE เรียกว่า actions) **ไม่ได้อยู่ในตารางนี้** — L2 §5.2
-- (v0.18/v0.19) จองคอลัมน์ `card.tap_areas` ไว้ให้เรื่องนี้อยู่แล้ว พร้อมหมายเหตุตรงตัว
-- ว่า "ริชเมสเสจ และริชวิดีโอ ... พิกัดพื้นที่กดบนภาพขนาดอ้างอิง 1040 · รองรับแค่
-- ข้อความและลิงก์ ไม่มี postback (BR-47)" — ตรงกับสิ่งที่สไลซ์นี้ต้องเก็บทุกตัวอักษร
-- การเปิดคอลัมน์ใหม่ซ้ำความหมายเดิมในตารางนี้จะได้ข้อเท็จจริงเดียวกันสองที่เก็บ ซึ่ง
-- เป็นสิ่งที่ทั้ง lib/db/cards.ts (used_by) และ lib/db/assets.ts (used_by) เขียนไว้
-- ตรงกันว่าเป็นด่านที่ไม่มีทางถูกเสมอ — ที่นี่จึงเขียนแค่ส่วนที่เอกสารยังไม่มีที่เก็บให้
--
-- asset.imagemap_base_url ก็ถูกจองไว้แล้วเช่นกัน ("path ฐานที่ใต้มันมีภาพ 5 ขนาด ...
-- ระบบสร้างให้อัตโนมัติตอนอัปโหลด") แต่คำอธิบายเต็มของคอลัมน์นั้นผูกกับกลไก DD-15
-- แบบเต็มรูป (วาดภาพจาก card_block ชุดเดียวกับ Flex ล่วงหน้าตอน publish คูณด้วยทุก
-- สถานะที่เป็นไปได้ของ selector — §4.4 ขั้น 5a, BR-80) ซึ่งเป็นงานคนละขนาดและยังค้าง
-- อยู่ที่ OI-25 (ต้นทุนเวลา/พื้นที่ของการวาดล่วงหน้า) — สไลซ์นี้ทำแค่กรณีภาพเดียวไม่มี
-- สถานะ (ไม่มี selector) คนตั้งค่าอัปโหลดภาพเองแล้วลากวาดพื้นที่กด ไม่ใช่วาดจากบล็อก
-- อัตโนมัติ ตารางนี้จึงเก็บเฉพาะบัญชีของภาพต้นฉบับกับภาพ 5 ขนาดที่ปั้นไว้ของกรณีนั้น
-- ส่วน asset.imagemap_base_url ยังคงถูกเติมค่าไว้ (ที่ applyImagemap()) เพื่อให้ตรงตาม
-- ที่เอกสารบอกว่า "ระบบสร้างให้อัตโนมัติตอนอัปโหลด" แต่โค้ดที่นี่ไม่ได้อ่านค่านั้นกลับ
-- มาใช้ — อ่านจาก variant_assets ของตารางนี้แทน เพราะรู้แน่ชัดกว่าว่าไฟล์ไหนคือไฟล์
-- ของขนาดไหนของการ์ดใบไหน โดยไม่ต้องแยกวิเคราะห์ path string
--
-- แยกเป็นคนละตารางจาก `card` โดยตั้งใจ ด้วยเหตุผลเดียวกับ 0007_richmenu_composition.sql:
-- `card` เป็นแถวที่ถูกอ่าน/เขียนบ่อยจากโค้ดที่ไม่เกี่ยวกับริชเมสเสจเลย (has_sample_text,
-- template_code ฯลฯ) การแปะบัญชีภาพ 5 ขนาดที่เปลี่ยนทุกครั้งที่กด "ใช้" ไว้บนแถวเดียวกัน
-- จะทำให้ทุกคำสั่งเขียนที่ไม่เกี่ยวข้องลาก JSON ก้อนนี้ไปเขียนทับเปล่าๆ (MVCC ของ
-- Postgres เขียนทั้งแถวใหม่ทุกครั้งที่ UPDATE ไม่ว่าจะแก้กี่คอลัมน์)
--
-- ไม่มีแถวในตารางนี้ = การ์ดใบนี้ยังไม่เคยอัปโหลดภาพฐานเลย (จอเริ่มจากพื้นเปล่า
-- เหมือนตัวจัดวางภาพของ Rich Menu ที่ยังไม่เคยเปิดเลย)
-- ─────────────────────────────────────────────────────────────────────────────

CREATE TABLE card_imagemap (
  id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  card_id        UUID NOT NULL UNIQUE REFERENCES card(id) ON DELETE CASCADE,
  -- ภาพต้นฉบับที่คนอัปโหลด · null ได้ก่อนอัปโหลดครั้งแรก
  base_asset_id  UUID REFERENCES asset(id),
  -- ขนาดจริงของภาพที่แปลง 1040px กว้างแล้ว (BR-46 · LINE ขอ baseSize ตามขนาดใหญ่สุด)
  -- ไม่ใช่ขนาดของไฟล์ที่คนอัปโหลดตรงๆ — null จนกว่าจะรู้สัดส่วนภาพจริง
  base_width     INTEGER,
  base_height    INTEGER,
  alt_text       TEXT NOT NULL DEFAULT '',
  -- {"240": assetId, "300": assetId, "460": assetId, "700": assetId, "1040": assetId}
  -- ว่างจนกว่าจะกด "ใช้" ครั้งแรก (ปั้นภาพ 5 ขนาดจริงแล้วค่อยเติม)
  variant_assets JSONB NOT NULL DEFAULT '{}',
  updated_by     UUID NOT NULL REFERENCES app_user(id),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
